# String Demo
course = "Python For Beginners"
print(course.upper())
print(course)
print("find Python in string "+ str(course.find('Python')))
print("find y in string "+ str(course.find('y')))
print("find Y in string "+ str(course.find('Y')))
print("replace For in string "+ str(course.replace('For','4')))
print(course)
print("replace x in string "+ str(course.replace('x','4')))
print("find Python in string "+ str('Python' in course))
